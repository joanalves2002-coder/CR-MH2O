"""Base de données : utilisateurs, chantiers, accès et comptes rendus.

- Avec Supabase (secrets renseignés) : base PostgreSQL hébergée, les données sont conservées.
- Sans Supabase : base SQLite locale (pour tester sur un ordinateur).
Les deux modes utilisent exactement les mêmes fonctions.
"""
import os
import sqlite3
from datetime import datetime

import auth
import config

# ---------------------------------------------------------------------
# Création des tables
# ---------------------------------------------------------------------
SCHEMA_SQLITE = """
CREATE TABLE IF NOT EXISTS utilisateurs (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    nom TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    mdp_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('admin', 'utilisateur')),
    actif INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS chantiers (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    nom TEXT NOT NULL,
    ville TEXT,
    maitre_ouvrage TEXT,
    statut TEXT NOT NULL DEFAULT 'En cours',
    cree_le TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS acces (
    utilisateur_id INTEGER NOT NULL REFERENCES utilisateurs(id),
    chantier_id INTEGER NOT NULL REFERENCES chantiers(id),
    droit TEXT NOT NULL CHECK (droit IN ('redaction', 'lecture')),
    PRIMARY KEY (utilisateur_id, chantier_id)
);
CREATE TABLE IF NOT EXISTS comptes_rendus (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    chantier_id INTEGER NOT NULL REFERENCES chantiers(id),
    numero INTEGER NOT NULL,
    date_reunion TEXT NOT NULL,
    auteur_id INTEGER REFERENCES utilisateurs(id),
    statut TEXT NOT NULL CHECK (statut IN ('Brouillon', 'Validé', 'Diffusé')),
    fichier TEXT NOT NULL,
    texte TEXT,
    cree_le TEXT NOT NULL,
    UNIQUE (chantier_id, numero)
);
"""

SCHEMA_POSTGRES = """
CREATE TABLE IF NOT EXISTS utilisateurs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    mdp_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('admin', 'utilisateur')),
    actif INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS chantiers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom TEXT NOT NULL,
    ville TEXT,
    maitre_ouvrage TEXT,
    statut TEXT NOT NULL DEFAULT 'En cours',
    cree_le TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS acces (
    utilisateur_id BIGINT NOT NULL REFERENCES utilisateurs(id),
    chantier_id BIGINT NOT NULL REFERENCES chantiers(id),
    droit TEXT NOT NULL CHECK (droit IN ('redaction', 'lecture')),
    PRIMARY KEY (utilisateur_id, chantier_id)
);
CREATE TABLE IF NOT EXISTS comptes_rendus (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chantier_id BIGINT NOT NULL REFERENCES chantiers(id),
    numero INTEGER NOT NULL,
    date_reunion TEXT NOT NULL,
    auteur_id BIGINT REFERENCES utilisateurs(id),
    statut TEXT NOT NULL CHECK (statut IN ('Brouillon', 'Validé', 'Diffusé')),
    fichier TEXT NOT NULL,
    texte TEXT,
    cree_le TEXT NOT NULL,
    UNIQUE (chantier_id, numero)
);
-- Sécurité : personne ne peut lire ces tables via l'API publique de Supabase.
-- Seule l'appli (connectée avec le mot de passe de la base) y a accès.
ALTER TABLE utilisateurs ENABLE ROW LEVEL SECURITY;
ALTER TABLE chantiers ENABLE ROW LEVEL SECURITY;
ALTER TABLE acces ENABLE ROW LEVEL SECURITY;
ALTER TABLE comptes_rendus ENABLE ROW LEVEL SECURITY;
"""


def postgres():
    return bool(_url_postgres())


def _url_postgres():
    return config.secret("SUPABASE_DB_URL") or os.environ.get("CR_TEST_PG_URL")


# ---------------------------------------------------------------------
# Connexion (une connexion réutilisée, reconnectée si elle tombe)
# ---------------------------------------------------------------------
_connexion_pg = None


def _pg():
    global _connexion_pg
    import psycopg
    from psycopg.rows import dict_row

    if _connexion_pg is None or _connexion_pg.closed:
        _connexion_pg = psycopg.connect(_url_postgres(), autocommit=True, row_factory=dict_row, connect_timeout=15)
    return _connexion_pg


def _sqlite():
    os.makedirs(config.DOSSIER_DONNEES, exist_ok=True)
    con = sqlite3.connect(os.path.join(config.DOSSIER_DONNEES, "appli_cr.db"))
    con.row_factory = sqlite3.Row
    con.execute("PRAGMA foreign_keys = ON")
    return con


def _executer(sql, params=(), lignes=True):
    """Exécute une requête écrite avec des '?' et renvoie une liste de dictionnaires."""
    if postgres():
        import psycopg

        sql_pg = sql.replace("?", "%s")
        for essai in range(2):
            try:
                with _pg().cursor() as cur:
                    cur.execute(sql_pg, params)
                    return [dict(r) for r in cur.fetchall()] if (lignes and cur.description) else []
            except psycopg.OperationalError:
                global _connexion_pg
                _connexion_pg = None  # connexion perdue : on se reconnecte une fois
                if essai == 1:
                    raise
    con = _sqlite()
    try:
        with con:
            cur = con.execute(sql, params)
            return [dict(r) for r in cur.fetchall()] if (lignes and cur.description) else []
    finally:
        con.close()


def _une(sql, params=()):
    r = _executer(sql, params)
    return r[0] if r else None


def initialiser():
    if postgres():
        with _pg().cursor() as cur:
            cur.execute(SCHEMA_POSTGRES)
    else:
        con = _sqlite()
        try:
            con.executescript(SCHEMA_SQLITE)
        finally:
            con.close()


def maintenant():
    return datetime.now().isoformat(timespec="seconds")


# ---------- Utilisateurs ----------
def nb_utilisateurs():
    return _une("SELECT COUNT(*) AS n FROM utilisateurs")["n"]


def creer_utilisateur(nom, email, mot_de_passe, role="utilisateur"):
    _executer(
        "INSERT INTO utilisateurs (nom, email, mdp_hash, role) VALUES (?, ?, ?, ?)",
        (nom.strip(), email.strip().lower(), auth.hacher(mot_de_passe), role),
        lignes=False,
    )


def authentifier(email, mot_de_passe):
    u = _une("SELECT * FROM utilisateurs WHERE email = ? AND actif = 1", (email.strip().lower(),))
    if u and auth.verifier(mot_de_passe, u["mdp_hash"]):
        return u
    return None


def liste_utilisateurs():
    return _executer("SELECT id, nom, email, role, actif FROM utilisateurs ORDER BY nom")


def changer_mot_de_passe(utilisateur_id, nouveau):
    _executer("UPDATE utilisateurs SET mdp_hash = ? WHERE id = ?", (auth.hacher(nouveau), utilisateur_id), lignes=False)


def activer_utilisateur(utilisateur_id, actif):
    _executer("UPDATE utilisateurs SET actif = ? WHERE id = ?", (1 if actif else 0, utilisateur_id), lignes=False)


# ---------- Chantiers et accès ----------
def creer_chantier(nom, ville="", maitre_ouvrage=""):
    r = _une(
        "INSERT INTO chantiers (nom, ville, maitre_ouvrage, cree_le) VALUES (?, ?, ?, ?) RETURNING id",
        (nom.strip(), ville.strip(), maitre_ouvrage.strip(), maintenant()),
    )
    return r["id"]


def modifier_statut_chantier(chantier_id, statut):
    _executer("UPDATE chantiers SET statut = ? WHERE id = ?", (statut, chantier_id), lignes=False)


def chantier(chantier_id):
    return _une("SELECT * FROM chantiers WHERE id = ?", (chantier_id,))


def tous_les_chantiers():
    return _executer("SELECT * FROM chantiers ORDER BY nom")


def chantiers_visibles(utilisateur):
    """L'admin voit tout ; les autres ne voient que les chantiers qui leur sont attribués."""
    dernier = "(SELECT MAX(numero) FROM comptes_rendus cr WHERE cr.chantier_id = c.id) AS dernier_numero"
    ordre = "ORDER BY CASE WHEN c.statut = 'En cours' THEN 0 ELSE 1 END, c.nom"
    if utilisateur["role"] == "admin":
        return _executer(f"SELECT c.*, 'redaction' AS droit, {dernier} FROM chantiers c {ordre}")
    return _executer(
        f"SELECT c.*, a.droit, {dernier} FROM chantiers c "
        f"JOIN acces a ON a.chantier_id = c.id AND a.utilisateur_id = ? {ordre}",
        (utilisateur["id"],),
    )


def droit_sur_chantier(utilisateur, chantier_id):
    """Renvoie 'redaction', 'lecture' ou None."""
    if utilisateur["role"] == "admin":
        return "redaction"
    r = _une("SELECT droit FROM acces WHERE utilisateur_id = ? AND chantier_id = ?", (utilisateur["id"], chantier_id))
    return r["droit"] if r else None


def donner_acces(utilisateur_id, chantier_id, droit):
    _executer(
        "INSERT INTO acces (utilisateur_id, chantier_id, droit) VALUES (?, ?, ?) "
        "ON CONFLICT (utilisateur_id, chantier_id) DO UPDATE SET droit = excluded.droit",
        (utilisateur_id, chantier_id, droit),
        lignes=False,
    )


def retirer_acces(utilisateur_id, chantier_id):
    _executer("DELETE FROM acces WHERE utilisateur_id = ? AND chantier_id = ?", (utilisateur_id, chantier_id), lignes=False)


def equipe_chantier(chantier_id):
    return _executer(
        "SELECT u.id, u.nom, u.email, a.droit FROM acces a JOIN utilisateurs u ON u.id = a.utilisateur_id "
        "WHERE a.chantier_id = ? ORDER BY u.nom",
        (chantier_id,),
    )


# ---------- Comptes rendus ----------
def ajouter_cr(chantier_id, numero, date_reunion, auteur_id, statut, fichier, texte):
    r = _une(
        "INSERT INTO comptes_rendus (chantier_id, numero, date_reunion, auteur_id, statut, fichier, texte, cree_le) "
        "VALUES (?, ?, ?, ?, ?, ?, ?, ?) RETURNING id",
        (chantier_id, numero, date_reunion, auteur_id, statut, fichier, texte, maintenant()),
    )
    return r["id"]


def crs_du_chantier(chantier_id):
    return _executer(
        "SELECT cr.*, u.nom AS auteur FROM comptes_rendus cr LEFT JOIN utilisateurs u ON u.id = cr.auteur_id "
        "WHERE cr.chantier_id = ? ORDER BY cr.numero DESC",
        (chantier_id,),
    )


def dernier_cr(chantier_id):
    crs = crs_du_chantier(chantier_id)
    return crs[0] if crs else None


def changer_statut_cr(cr_id, statut):
    _executer("UPDATE comptes_rendus SET statut = ? WHERE id = ?", (statut, cr_id), lignes=False)


def supprimer_cr(cr_id):
    r = _une("SELECT fichier FROM comptes_rendus WHERE id = ?", (cr_id,))
    _executer("DELETE FROM comptes_rendus WHERE id = ?", (cr_id,), lignes=False)
    return r["fichier"] if r else None


def rechercher(utilisateur, terme):
    ids = [c["id"] for c in chantiers_visibles(utilisateur)]
    if not ids or not terme.strip():
        return []
    marques = ",".join("?" * len(ids))
    comparaison = "ILIKE" if postgres() else "LIKE"
    return _executer(
        f"SELECT cr.id, cr.numero, cr.date_reunion, cr.texte, cr.fichier, cr.statut, c.nom AS chantier, c.id AS chantier_id "
        f"FROM comptes_rendus cr JOIN chantiers c ON c.id = cr.chantier_id "
        f"WHERE cr.chantier_id IN ({marques}) AND cr.texte {comparaison} ? ORDER BY cr.date_reunion DESC LIMIT 50",
        (*ids, f"%{terme.strip()}%"),
    )


def exporter_tout():
    """Toutes les tables (sauf les mots de passe) pour la sauvegarde."""
    return {
        "utilisateurs": liste_utilisateurs(),
        "chantiers": tous_les_chantiers(),
        "acces": _executer("SELECT * FROM acces"),
        "comptes_rendus": _executer("SELECT id, chantier_id, numero, date_reunion, auteur_id, statut, fichier, cree_le FROM comptes_rendus"),
    }
